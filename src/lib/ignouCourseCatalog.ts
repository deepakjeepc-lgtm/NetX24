/**
 * Normalizes a course code key for flexible matching (e.g., "BHDC 101" === "BHDC-101" === "BHDC101")
 */
export function normalizeCourseCodeKey(code: string): string {
  return (code || '').trim().toUpperCase().replace(/[\s\-_]+/g, '');
}

const NORMALIZED_TITLE_LOOKUP: Map<string, { canonicalCode: string; title: string }> = (() => {
  const map = new Map<string, { canonicalCode: string; title: string }>();
  for (const [code, title] of Object.entries(IGNOU_MASTER_COURSE_TITLES)) {
    map.set(normalizeCourseCodeKey(code), { canonicalCode: code, title });
  }
  return map;
})();

export function lookupIgnouCourseTitle(code: string): string | undefined {
  const key = normalizeCourseCodeKey(code);
  return NORMALIZED_TITLE_LOOKUP.get(key)?.title;
}

function buildYearCourses(
  yearMap: Partial<Record<IgnouYear, Array<string | { code: string; title: string }>>>
): IgnouCourseEntry[] {
  const entries: IgnouCourseEntry[] = [];
  const years: IgnouYear[] = ['1st Year', '2nd Year', '3rd Year', '4th Year'];

  for (const year of years) {
    const rawList = yearMap[year];
    if (!rawList) continue;
    for (const item of rawList) {
      if (typeof item === 'string') {
        const cleanCode = item.trim().toUpperCase();
        const title =
          IGNOU_MASTER_COURSE_TITLES[cleanCode] ||
          lookupIgnouCourseTitle(cleanCode) ||
          cleanCode;
        entries.push({ code: cleanCode, title, year });
      } else {
        const cleanCode = item.code.trim().toUpperCase();
        const title =
          item.title.trim() ||
          IGNOU_MASTER_COURSE_TITLES[cleanCode] ||
          lookupIgnouCourseTitle(cleanCode) ||
          cleanCode;
        entries.push({ code: cleanCode, title, year });
      }
    }
  }
  return entries;
}

