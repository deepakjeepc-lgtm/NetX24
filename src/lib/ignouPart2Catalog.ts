function makeCourses(
  codes: string[],
  year: IgnouYear = '1st Year'
): IgnouCourseEntry[] {
  return codes.map((raw) => {
    const code = raw.trim().toUpperCase();
    const title = IGNOU_PART2_COURSE_TITLES[code] || code;
    return { code, title, year };
  });
}

function makeMultiYearCourses(
  yearMap: Partial<Record<IgnouYear, string[]>>
): IgnouCourseEntry[] {
  const result: IgnouCourseEntry[] = [];
  const years: IgnouYear[] = ['1st Year', '2nd Year', '3rd Year', '4th Year'];
  for (const yr of years) {
    const list = yearMap[yr];
    if (list && list.length > 0) {
      result.push(...makeCourses(list, yr));
    }
  }
  return result;
}

